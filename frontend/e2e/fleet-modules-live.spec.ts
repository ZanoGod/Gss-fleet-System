import { expect, test } from '@playwright/test'

// This workflow uses a seeded, isolated QA database. Never point it at production.
test.skip(!process.env.GSS_LIVE_QA_URL, 'Set GSS_LIVE_QA_URL for the isolated QA application.')
test.use({ baseURL: process.env.GSS_LIVE_QA_URL })
test('fleet, operator and maintenance records persist through real API requests', async ({
  page,
}) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const suffix = Date.now().toString()
  await page.goto('/login')
  await page.getByLabel('Username or email').fill('modules.qa')
  await page.getByLabel('Password', { exact: true }).fill('GssModulesQA2026!')
  await page.getByRole('button', { name: 'Secure Login' }).click()
  await expect(page).toHaveURL(/dashboard/)

  await page.getByRole('link', { name: 'Cars / Vehicles' }).click()
  await page.getByRole('link', { name: '+ Add Vehicle', exact: true }).click()
  await page.getByLabel('Car Type').fill('Van')
  await page.getByLabel('Plate Number').fill(`QA-${suffix}`)
  await page.getByLabel('Model / Year').fill('Hiace 2026')
  await page.getByRole('button', { name: 'Save Vehicle', exact: true }).click()
  await expect(page).toHaveURL(/notice=saved/)
  await expect(page.getByText('Vehicle saved successfully.', { exact: true })).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search', exact: true }).fill(`QA-${suffix}`)
  await page.getByRole('button', { name: 'Filter', exact: true }).click()
  await expect(page).toHaveURL(/search=/)
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.getByRole('cell', { name: `QA-${suffix}`, exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('cell', { name: `QA-${suffix}`, exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/fleet-desktop.png', fullPage: true })
  await page.getByRole('link', { name: 'View', exact: true }).click()
  await expect(page).toHaveURL(/\/fleet\/\d+\?/)
  const vehicleUrl = page.url()
  await page.getByRole('link', { name: 'Edit Vehicle', exact: true }).click()
  await page.getByLabel('Notes').fill('Verified persisted edit')
  await page.getByRole('button', { name: 'Save Vehicle', exact: true }).click()
  await expect(page).toHaveURL(/notice=saved/)
  await page.goto(vehicleUrl)
  await expect(page.getByText('Verified persisted edit', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Schedule maintenance', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Vehicle', exact: true })).toHaveValue(/daily:/)
  await page.getByLabel('Title').fill(`Oil service ${suffix}`)
  await page.getByLabel('Scheduled Date').fill('2026-11-02')
  await page.getByLabel('Currency Code').fill('USD')
  await page.getByLabel('Estimated Cost').fill('50.00')
  await page.getByRole('button', { name: 'Save Maintenance Record', exact: true }).click()
  await expect(page).toHaveURL(/notice=saved/)
  await expect(page.getByRole('cell', { name: `Oil service ${suffix}`, exact: true })).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search', exact: true }).fill(`Oil service ${suffix}`)
  await page.getByRole('button', { name: 'Filter', exact: true }).click()
  await expect(page).toHaveURL(/search=/)
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('link', { name: 'Edit', exact: true }).click()
  await expect(page).toHaveURL(/maintenance\/\d+\/edit/)
  await page
    .getByRole('combobox', { name: 'Work Order Status', exact: true })
    .selectOption('In Progress')
  await page.getByRole('button', { name: 'Save Maintenance Record', exact: true }).click()
  await expect(page).toHaveURL(/notice=saved/)
  await page.goto(vehicleUrl)
  await expect(page.getByText(`Oil service ${suffix}`, { exact: true })).toBeVisible()
  await page.getByRole('link', { name: `Oil service ${suffix}`, exact: true }).click()
  await page.getByRole('link', { name: 'Edit Maintenance Record', exact: true }).click()
  await expect(page).toHaveURL(/maintenance\/\d+\/edit/)
  await page
    .getByRole('combobox', { name: 'Work Order Status', exact: true })
    .selectOption('Completed')
  await page.getByLabel('Actual Cost').fill('45.25')
  await page.getByRole('button', { name: 'Save Maintenance Record', exact: true }).click()
  await expect(page).toHaveURL(/notice=saved/)
  await expect(page.getByText('45.25').first()).toBeVisible()
  await page.reload()
  await expect(page.getByText('Completed', { exact: true }).last()).toBeVisible()
  await page.screenshot({ path: 'test-results/maintenance-desktop.png', fullPage: true })
  await page.goto(vehicleUrl)
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Delete record', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('history')

  await page.goto('/fleet?resource_type=monthly')
  await page.getByRole('link', { name: '+ Add Vehicle', exact: true }).click()
  await page.getByLabel('Car Type').fill('Sedan')
  await page.getByLabel('Plate Number').fill(`QM-${suffix}`)
  await page.getByLabel('Model / Year').fill('Monthly 2026')
  await page.getByLabel('Stored Status').selectOption('Inactive')
  await page.getByRole('button', { name: 'Save Vehicle', exact: true }).click()
  await expect(page).toHaveURL(/notice=saved/)
  await expect(page.getByRole('cell', { name: `QM-${suffix}`, exact: true })).toBeVisible()

  await page.goto('/operators/create')
  await page.getByLabel('Operator Name').fill(`Dispatch ${suffix}`)
  await page.getByLabel('Phone Number').fill('0912345678')
  await page.getByRole('button', { name: 'Save Operator', exact: true }).click()
  await expect(page).toHaveURL(/notice=saved/)
  await page.getByRole('searchbox', { name: 'Search', exact: true }).fill(`Dispatch ${suffix}`)
  await page.getByRole('button', { name: 'Filter', exact: true }).click()
  await expect(page).toHaveURL(/search=/)
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('cell', { name: `Dispatch ${suffix}`, exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.app-main')).toHaveCSS('margin-left', '0px')
  await expect(page.locator('.sidebar')).toHaveCSS('visibility', 'hidden')
  await page.screenshot({ path: 'test-results/operators-mobile.png', fullPage: true })
  await page.getByRole('link', { name: 'View', exact: true }).click()
  await expect(page).toHaveURL(/\/operators\/\d+$/)
  const operatorUrl = page.url()
  await page.getByRole('link', { name: 'Edit Operator', exact: true }).click()
  await page.getByLabel('Phone Number').fill('0998765432')
  await page.getByRole('button', { name: 'Save Operator', exact: true }).click()
  await expect(page).toHaveURL(/notice=saved/)
  await page.goto(operatorUrl)
  await expect(page.getByText('0998765432', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Delete record', exact: true }).click()
  await expect(page.getByText('Operator deleted.', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
